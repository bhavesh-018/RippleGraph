"""
RippleGraph - Server-Sent Events (SSE) Schemas

Defines type-safe Pydantic v2 event models for real-time live graph animation
and pipeline reasoning streaming:
  - STAGE_CHANGED: Pipeline transitions through Stages 1-4
  - CONSUMERS_FOUND: Direct dependents identified via Cypher
  - COMPATIBILITY_CHECKED: Individual service contract verification result
  - DOWNSTREAM_PATH: Multi-hop traversal path discovery
  - MEMORY_RECALLED: Historical findings retrieved from FalkorDB with decay
  - FINDING_PRODUCED: Final scored finding generated by reviewer
  - COMPLETE: Pipeline terminal state with summary metrics
"""

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class SSEEventType(str, Enum):
    STAGE_CHANGED = "STAGE_CHANGED"
    CONSUMERS_FOUND = "CONSUMERS_FOUND"
    COMPATIBILITY_CHECKED = "COMPATIBILITY_CHECKED"
    DOWNSTREAM_PATH = "DOWNSTREAM_PATH"
    MEMORY_RECALLED = "MEMORY_RECALLED"
    FINDING_PRODUCED = "FINDING_PRODUCED"
    COMPLETE = "COMPLETE"


class StageChangedPayload(BaseModel):
    stage_id: str
    stage_name: str
    description: str


class ConsumersFoundPayload(BaseModel):
    api_id: str
    consumer_service_ids: List[str]


class CompatibilityCheckedPayload(BaseModel):
    service_id: str
    service_name: str
    status: str
    contract_id: str
    missing_claims: List[str] = Field(default_factory=list)


class DownstreamPathPayload(BaseModel):
    path: List[str]
    depth: int
    status: str = "potential_downstream"


class MemoryRecalledPayload(BaseModel):
    findings_count: int
    prior_finding_ids: List[str] = Field(default_factory=list)
    applied_to_services: List[str] = Field(default_factory=list)


class FindingProducedPayload(BaseModel):
    finding_id: str
    service_id: str
    service_name: Optional[str] = None
    category: str
    status: str
    confidence: float
    hop_depth: int = 0


class CompletePayload(BaseModel):
    investigation_id: str
    change_id: str
    summary: Dict[str, int]
    recommended_contract: Optional[str] = None
    execution_time_ms: float


class SSEMessage(BaseModel):
    event: SSEEventType
    data: Dict[str, Any]

    def to_sse_format(self) -> str:
        """Serialize as standard W3C text/event-stream line-based string."""
        import json
        return f"event: {self.event.value}\ndata: {json.dumps(self.data)}\n\n"
